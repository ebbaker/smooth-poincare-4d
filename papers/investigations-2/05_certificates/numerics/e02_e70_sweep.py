#!/usr/bin/env python3
"""Bounded baseline for SP4-CERT-E02, 27 November 2026, for Edward B. Baker III.

Prepared with OpenAI assistance. Actual model and effort unavailable.
Inputs are E70 §3 and master check_05 at HEAD 6a422ce, respectively
SHA-256 prefixes ade2987d8bf24aa9 and 30861b3f4c89323c. The HLT engine
and the word encoding are adapted from check_05. Each worker is run in a
separate process and uses at most 20,000 provisional rows and 60 seconds.
The run is conditional on E70's relators. Closure is diagnostic only.
No other searches are performed.
"""

import argparse
from pathlib import Path
import subprocess
import sys

COS_LIMIT = 20_000
SECONDS = 60


def coset_enumeration(ngens, relators, subgens=(), max_cosets=20_000):
    """Generators are 1..ngens, inverses are negative.  Returns the number of cosets of the
    subgroup generated by subgens (words), or None if the cap is reached without closure."""
    cols = list(range(1, ngens + 1)) + [-g for g in range(1, ngens + 1)]
    idx = {g: i for i, g in enumerate(cols)}
    inv = {g: idx[-g] for g in cols}
    table = [[None] * len(cols)]
    parent = [0]
    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a
    queue = []
    def merge(a, b):
        a, b = find(a), find(b)
        if a == b:
            return
        if a > b:
            a, b = b, a
        parent[b] = a
        queue.append(b)
    def process():
        while queue:
            b = queue.pop()
            for g in cols:
                d = table[b][idx[g]]
                if d is None:
                    continue
                table[b][idx[g]] = None
                d0 = find(d)
                if table[d][inv[g]] == b:
                    table[d][inv[g]] = None
                a = find(b)
                d0 = find(d)
                e = table[a][idx[g]]
                if e is None:
                    table[a][idx[g]] = d0
                    if table[d0][inv[g]] is None:
                        table[d0][inv[g]] = a
                    else:
                        merge(table[d0][inv[g]], a)
                else:
                    merge(e, d0)
                    f = table[d0][inv[g]]
                    if f is None:
                        table[d0][inv[g]] = a
                    else:
                        merge(f, a)
    def define(a, g):
        if len(table) >= max_cosets:
            raise OverflowError
        table.append([None] * len(cols))
        parent.append(len(table) - 1)
        n = len(table) - 1
        table[a][idx[g]] = n
        table[n][inv[g]] = a
        return n
    def scan_and_fill(a, word):
        a = find(a)
        f, i = a, 0
        b, j = a, len(word) - 1
        while True:
            while i <= j and table[f][idx[word[i]]] is not None:
                f = find(table[f][idx[word[i]]]); i += 1
            if i > j:
                if f != b:
                    merge(f, b); process()
                return
            while j >= i and table[b][inv[word[j]]] is not None:
                b = find(table[b][inv[word[j]]]); j -= 1
            if j < i:
                merge(f, b); process()
                return
            if j == i:
                g = word[i]
                table[f][idx[g]] = b
                table[b][inv[g]] = f
                return
            f = define(f, word[i]); i += 1
            if len(table) > max_cosets:
                raise OverflowError
    try:
        for w in subgens:
            scan_and_fill(0, w)
        a = 0
        while a < len(table):
            if find(a) == a:
                for w in relators:
                    scan_and_fill(a, w)
                    if find(a) != a:
                        break
                if find(a) == a:
                    for g in cols:
                        if table[a][idx[g]] is None:
                            define(a, g)
            a += 1
    except OverflowError:
        return None, len(table)
    return sum(1 for a in range(len(table)) if find(a) == a), len(table)

Fg, Lg, bg, cg = 1, 2, 3, 4
def W(*parts):
    out = []
    for p in parts:
        out.extend(p)
    # free reduction
    red = []
    for g in out:
        if red and red[-1] == -g:
            red.pop()
        else:
            red.append(g)
    return red
def inv(w):
    return [-g for g in reversed(w)]
def power(w, n):
    return W(*([w] * n)) if n >= 0 else W(*([inv(w)] * (-n)))
def comm(x, y):
    return W(x, y, inv(x), inv(y))

F, L, b, c = [Fg], [Lg], [bg], [cg]
b1 = W(L, b, inv(L))
btop = W(F, b1, inv(F))
ctop = W(F, c, inv(F))
lamF = W(inv(c), inv(b), inv(L))
lamL = W(inv(b1), inv(F))
base = [power(b, 2), power(c, 2), comm(F, lamF), comm(L, lamL),
        W(power(W(b, btop), 2), power(W(ctop, btop), -3)),
        W(power(F, 3), power(lamF, -2))]

def filled(s):
    return base + [W(power(L, s - 1), lamL)]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--slope", type=int, choices=range(-3, 4))
    args = parser.parse_args()
    if args.slope is not None:
        count, used = coset_enumeration(4, filled(args.slope), max_cosets=COS_LIMIT)
        status = "cap reached" if count is None else f"closed at {count}"
        print(f"{args.slope:+}: {status}, provisional rows {used}")
        return

    for slope in range(-3, 4):
        argv = [sys.executable, str(Path(__file__).resolve()), "--slope", str(slope)]
        try:
            result = subprocess.run(argv, check=True, capture_output=True,
                                    text=True, timeout=SECONDS)
        except subprocess.TimeoutExpired:
            print(f"{slope:+}: {SECONDS}s timeout")
        else:
            print(result.stdout.strip())


if __name__ == "__main__":
    main()
