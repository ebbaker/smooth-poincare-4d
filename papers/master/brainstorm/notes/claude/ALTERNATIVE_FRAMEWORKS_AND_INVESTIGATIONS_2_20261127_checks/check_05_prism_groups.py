# ---------- a small Todd-Coxeter (HLT with coincidence handling) ----------
def coset_enumeration(ngens, relators, subgens=(), max_cosets=200000):
    """Generators are 1..ngens, inverses are negative.  Returns the number of cosets of the
    subgroup generated by subgens (words), or None if max_cosets is exceeded."""
    cols = list(range(1, ngens + 1)) + [-g for g in range(1, ngens + 1)]
    idx = {g: i for i, g in enumerate(cols)}
    inv = {g: idx[-g] for g in cols}
    table = [[None] * len(cols)]
    parent = [0]
    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a
    queue = []
    def merge(a, b):
        a, b = find(a), find(b)
        if a == b:
            return
        if a > b:
            a, b = b, a
        parent[b] = a
        queue.append(b)
    def process():
        while queue:
            b = queue.pop()
            for g in cols:
                d = table[b][idx[g]]
                if d is None:
                    continue
                table[b][idx[g]] = None
                d0 = find(d)
                if table[d][inv[g]] == b:
                    table[d][inv[g]] = None
                a = find(b)
                d0 = find(d)
                e = table[a][idx[g]]
                if e is None:
                    table[a][idx[g]] = d0
                    if table[d0][inv[g]] is None:
                        table[d0][inv[g]] = a
                    else:
                        merge(table[d0][inv[g]], a)
                else:
                    merge(e, d0)
                    f = table[d0][inv[g]]
                    if f is None:
                        table[d0][inv[g]] = a
                    else:
                        merge(f, a)
    def define(a, g):
        table.append([None] * len(cols))
        parent.append(len(table) - 1)
        n = len(table) - 1
        table[a][idx[g]] = n
        table[n][inv[g]] = a
        return n
    def scan_and_fill(a, word):
        a = find(a)
        f, i = a, 0
        b, j = a, len(word) - 1
        while True:
            while i <= j and table[f][idx[word[i]]] is not None:
                f = find(table[f][idx[word[i]]]); i += 1
            if i > j:
                if f != b:
                    merge(f, b); process()
                return
            while j >= i and table[b][inv[word[j]]] is not None:
                b = find(table[b][inv[word[j]]]); j -= 1
            if j < i:
                merge(f, b); process()
                return
            if j == i:
                g = word[i]
                table[f][idx[g]] = b
                table[b][inv[g]] = f
                return
            f = define(f, word[i]); i += 1
            if len(table) > max_cosets:
                raise OverflowError
    try:
        for w in subgens:
            scan_and_fill(0, w)
        a = 0
        while a < len(table):
            if find(a) == a:
                for w in relators:
                    scan_and_fill(a, w)
                    if find(a) != a:
                        break
                if find(a) == a:
                    for g in cols:
                        if table[a][idx[g]] is None:
                            define(a, g)
                            if len(table) > max_cosets:
                                raise OverflowError
            a += 1
    except OverflowError:
        return None
    return sum(1 for a in range(len(table)) if find(a) == a)

# ---------- words ----------
Fg, Lg, bg, cg = 1, 2, 3, 4
def W(*parts):
    out = []
    for p in parts:
        out.extend(p)
    # free reduction
    red = []
    for g in out:
        if red and red[-1] == -g:
            red.pop()
        else:
            red.append(g)
    return red
def inv(w):
    return [-g for g in reversed(w)]
def power(w, n):
    return W(*([w] * n)) if n >= 0 else W(*([inv(w)] * (-n)))
def comm(x, y):
    return W(x, y, inv(x), inv(y))

F, L, b, c = [Fg], [Lg], [bg], [cg]
b1 = W(L, b, inv(L))
btop = W(F, b1, inv(F))
ctop = W(F, c, inv(F))
lamF = W(inv(c), inv(b), inv(L))
lamL = W(inv(b1), inv(F))
base = [power(b, 2), power(c, 2), comm(F, lamF), comm(L, lamL),
        W(power(W(b, btop), 2), power(W(ctop, btop), -3)),
        W(power(F, 3), power(lamF, -2))]

def filled(s):
    return base + [W(power(L, s - 1), lamL)]

results = []
def check(name, cond):
    results.append(bool(cond))
    print(("ok   " if cond else "FAIL ") + name)

n816 = coset_enumeration(4, base + [L])
check(f"(1a) meridian of the regular knot killed: order {n816} = 816", n816 == 816)
n6 = coset_enumeration(4, filled(0))
check(f"(2a) slope a (s = 0): order {n6} = 6", n6 == 6)

# abelianizations by Smith normal form
import sympy as sp
from sympy.matrices.normalforms import smith_normal_form
def abelian_invariants(rels):
    M = sp.zeros(len(rels), 4)
    for i, w in enumerate(rels):
        for g in w:
            M[i, abs(g) - 1] += 1 if g > 0 else -1
    S = smith_normal_form(M, domain=sp.ZZ)
    d = [abs(S[i, i]) for i in range(min(S.shape))]
    return sorted(x for x in d if x != 1)
check(f"(1b) abelianization with L = 1 is {abelian_invariants(base + [L])}: cyclic of order 6", abelian_invariants(base + [L]) == [6])
n3 = coset_enumeration(4, base + [L, b, c])
check(f"(1c) underlying space of the orbit orbifold: order {n3} = 3, as for L(3,1)", n3 == 3)
ab = {s: abelian_invariants(filled(s)) for s in (-3, -2, -1, 0, 1, 2, 3)}
print("     abelian invariants of G_s:", ab)
check("(2b) abelianizations: s = 0 gives C_2, s = 1 gives C_4, s = -1 gives C_8", ab[0] == [2] and ab[1] == [4] and ab[-1] == [8])
# underlying space: kill the two order-two meridians
under = {s: coset_enumeration(4, filled(s) + [b, c]) for s in (-3, -2, -1, 0, 1, 2, 3)}
print("     orders after killing b and c:", under)
check("(2c) underlying-space groups have order |3s - 1|", all(under[s] == abs(3 * s - 1) for s in under))

# ---------- concrete model of G = (2T x Dic_17)/<(-1,-1)> ----------
def qmul(p, q):
    a1, b1_, c1, d1 = p; a2, b2, c2, d2 = q
    return (a1*a2 - b1_*b2 - c1*c2 - d1*d2, a1*b2 + b1_*a2 + c1*d2 - d1*c2,
            a1*c2 - b1_*d2 + c1*a2 + d1*b2, a1*d2 + b1_*c2 - c1*b2 + d1*a2)
one = (Fr(1), Fr(0), Fr(0), Fr(0))
qi, qj, qk = (Fr(0), Fr(1), Fr(0), Fr(0)), (Fr(0), Fr(0), Fr(1), Fr(0)), (Fr(0), Fr(0), Fr(0), Fr(1))
om = (Fr(1, 2), Fr(1, 2), Fr(1, 2), Fr(1, 2))
T2 = {one}
frontier = [one]
while frontier:
    new = []
    for x in frontier:
        for g in (qi, qj, om):
            y = qmul(x, g)
            if y not in T2:
                T2.add(y); new.append(y)
    frontier = new
assert len(T2) == 24
neg = lambda q: tuple(-x for x in q)
# Dic_17: elements zeta^a j^e, zeta of order 34, j^2 = zeta^17, j zeta j^-1 = zeta^-1
def dmul(x, y):
    (a, e), (a2, e2) = x, y
    if e == 0:
        return ((a + a2) % 34, e2)
    # zeta^a j zeta^a2 j^e2 = zeta^(a - a2) j^(1 + e2)
    if e2 == 0:
        return ((a - a2) % 34, 1)
    return ((a - a2 + 17) % 34, 0)
def canon(l, d):
    a, e = d
    if a >= 17:
        return (neg(l), ((a - 17) % 34, e))
    return (l, d)
elems = sorted({canon(l, (a, e)) for l in T2 for a in range(34) for e in (0, 1)})
assert len(elems) == 816
index = {x: i for i, x in enumerate(elems)}
def gmul(x, y):
    return index[canon(qmul(elems[x][0], elems[y][0]), dmul(elems[x][1], elems[y][1]))]
n = len(elems)
mult = np.empty((n, n), dtype=np.int32)
for x in range(n):
    for y in range(n):
        mult[x, y] = gmul(x, y)
ident = index[canon(one, (0, 0))]
invt = np.empty(n, dtype=np.int32)
for x in range(n):
    invt[x] = int(np.where(mult[x] == ident)[0][0])
check("(3a) concrete model of (2T x Dic_17)/<(-1,-1)> has 816 elements and is a group",
      all(mult[mult[x, 5], 7] == mult[x, mult[5, 7]] for x in range(0, n, 37)))

def ev(word, img):
    """img: dict generator -> element index or numpy vector of indices."""
    acc = None
    for g in word:
        x = img[abs(g)]
        if g < 0:
            x = invt[x]
        acc = x if acc is None else mult[acc, x]
    return acc

invols = [x for x in range(n) if x != ident and mult[x, x] == ident]
print("     involutions in the model:", len(invols))
rels1 = [w for w in base]                       # relators with L = 1 substituted below
allF = np.arange(n, dtype=np.int32)
found = None
count = 0
for bi in invols:
    for ci in invols:
        img = {Fg: allF, Lg: np.full(n, ident, dtype=np.int32), bg: np.full(n, bi, dtype=np.int32), cg: np.full(n, ci, dtype=np.int32)}
        ok = np.ones(n, dtype=bool)
        for w in rels1:
            ok &= (ev(w, img) == ident)
            if not ok.any():
                break
        for fi in np.nonzero(ok)[0]:
            # generated subgroup
            gens = [int(fi), bi, ci]
            seen = {ident}; fr = [ident]
            while fr:
                nw = []
                for x in fr:
                    for g in gens:
                        y = int(mult[x, g])
                        if y not in seen:
                            seen.add(y); nw.append(y)
                fr = nw
            count += 1
            if len(seen) == n and found is None:
                found = (int(fi), bi, ci)
        if found:
            break
    if found:
        break
check(f"(3b) the presentation with L = 1 maps onto the model (images of F, b, c: {found}); with (1a) this is an isomorphism",
      found is not None)
if found:
    fi, bi, ci = found
    print("     image of F:", elems[fi], " order", next(k for k in range(1, 100) if ev([Fg] * k, {Fg: fi}) == ident))
    print("     image of b:", elems[bi]); print("     image of c:", elems[ci])

for s in (1, -1):
    m = coset_enumeration(4, filled(s), max_cosets=400000)
    print(f"info (4) slope a{'+' if s > 0 else '-'}mu: enumeration " + ("closed at order %d" % m if m else "did not close below 400000 cosets (consistent with an infinite group; not a proof)"))
